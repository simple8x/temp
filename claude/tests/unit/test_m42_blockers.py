"""Regression / adversarial tests for the three M4.2 blockers (see docs/M4_2_KICAD_EXPORT.md, "Hardening").

B1  S2 (MEASURED_STUB) lineage must be the measured segment that geometrically supports the pin.
B2  A PIN_LINES selection is audited against the source page's lines (fail / blocked, never silently verified).
B3  The ground-truth gate cannot PASS on zero / insufficient mapped pins and needs an explicit policy.

Page geometry here is the vector ingest of PDFs GENERATED by the test helpers (pdfgen / render_kicad), not of a
real source schematic PDF: these tests show the checks work on ingested geometry, nothing more.
"""
