# ======================================================================== B1: S2 provenance / geometry
def _pin_with_stub(conn):
    o = next(o for o in conn["objects"] if o["kind"] == "PIN" and o["pin"]["stub"])
    return o, o["pin"]["stub"]


def _reject(conn, needle):
    with pytest.raises(writer.DocumentError) as e:
        writer.loads(rehash_conn(conn))                 # re-hashing a forged document does not help
    assert any(needle in p for p in e.value.problems), e.value.problems


def test_b1_valid_s2_lineage_is_accepted_on_load_and_against_the_page():
    pi, conn, syms = docs(chain("r0"))
    stubs = [o["pin"]["stub"] for o in conn["objects"] if o["kind"] == "PIN"]
    assert stubs and all(s is not None for s in stubs)
    assert writer.s2_problems(conn) == [] and symrec.audit_evidence(conn, syms, pi, LIB) == []
    for o in conn["objects"]:
        if o["kind"] == "PIN":
            ev = next(e for e in conn["evidence"] if e["id"] == "S2:" + o["id"][2:])
            assert ev["lineage"] == [f"geom:{o['pin']['stub']['prim']}"]
            t, b = o["pin"]["tip"], o["pin"]["base"]
            plen = ((t[0] - b[0]) ** 2 + (t[1] - b[1]) ** 2) ** 0.5
            assert 0 < o["pin"]["stub"]["tolerance"] <= max(S2_TAU_ABS_MAX, S2_REL_MAX * plen) + 1e-12


