@pytest.mark.parametrize("scene", [chain("r0"), chain("dg"), crossing()], ids=lambda s: s.name)
def test_b1_existing_but_unrelated_primitive_is_rejected(scene):
    pi, conn, syms = docs(scene)
    o, st = _pin_with_stub(conn)
    other = next(p for p in conn["primitives"] if p["id"] != st["prim"]
                 and p["id"] not in {x["pin"]["stub"]["prim"] for x in conn["objects"] if x["kind"] == "PIN"})
    bad = copy.deepcopy(conn)
    bo = next(x for x in bad["objects"] if x["id"] == o["id"])
    bo["pin"]["stub"]["prim"] = other["id"]
    next(e for e in bad["evidence"] if e["id"] == "S2:" + o["id"][2:])["lineage"] = [f"geom:{other['id']}"]
    with pytest.raises(writer.DocumentError):
        writer.loads(rehash_conn(bad))
    # the page audit rejects it even when the file-level bbox check is not reached
    assert any("is not segment" in p or "outside the bbox" in p or "no segment" in p
               for p in symrec.audit_s2_against_page(bad, pi))
    # and the same forgery with the unrelated primitive's REAL segment does not span the pin
    q = next(q for q in pi.prims if q.id == other["id"])
    _, a, b = next(iter(q.segments()))
    bo["pin"]["stub"].update(a=list(map(float, a)), b=list(map(float, b)), segment=0)
    _reject(bad, "does not span base")


